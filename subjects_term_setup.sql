-- ============================================================
-- TaskFlow 科目学期分期：给 subjects 表加 term 字段
-- ------------------------------------------------------------
-- 学期 key 格式 `YYYY-N`：YYYY = 学年起始年，N = 1(秋/上学期) | 2(春/下学期)
--   2025-1 大一上  ·  2025-2 大一下  ·  2026-1 大二上  ·  2026-2 大二下
-- 在 Supabase → SQL Editor 里整段跑一次即可。
-- ============================================================

-- 1) 加列（可重复执行）
alter table public.subjects add column if not exists term text;

-- 2) 回填历史数据：现有的科目都是大一下学期的 → 2025-2
update public.subjects set term = '2025-2' where term is null;

-- 3) 查一下结果（应看到 2025-2 若干门）
select term, count(*) as 科目数 from public.subjects group by term order by term;


-- ============================================================
-- 说明
-- ------------------------------------------------------------
-- · 没跑这个脚本时，前端会把所有「没有 term 的」科目当作 2025-2（大一下）显示，
--   所以界面不会崩，但你导入大二上的课时会写入失败（前端会自动降级为不带 term 写入，
--   那种情况下大二上的课会被算进大一下）。
-- · 跑完这个脚本再导入，新课才会正确落进「大二上」。
-- · 入学年份写在 script.js 的 ENROLL_YEAR，目前是 2025。
--   以后若发现年级标错（比如显示成「大三上」），改那个常量即可，不用动数据库。
